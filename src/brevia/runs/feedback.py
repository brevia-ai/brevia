"""Feedback on runs: corrections of an output, or a rating, from the people who use it.

Feedback is only added: a later feedback never replaces an earlier one, and the output
of the run is never changed. Brevia keeps the differences and an opaque reference to
the final document, not the document itself: comparing a draft with its corrected
version is the work of the consumer project.
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal, Self

from pydantic import BaseModel, ConfigDict, Field, model_validator

MAX_ITEMS = 500
"""Most corrections in one feedback."""


class Correction(BaseModel):
    """A part of the output and its corrected text.

    Attributes:
        target: The part of the output, as the consumer names it, for example a
            field of the output or a section of the document.
        original: The text generated by the run.
        corrected: The text after the correction.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    target: str = Field(min_length=1, max_length=500)
    original: str
    corrected: str


class FeedbackRequest(BaseModel):
    """Feedback to add to a run: corrections, or a rating.

    Attributes:
        kind: ``"correction"`` with ``items``, or ``"rating"`` with ``rating``.
        source: Who gave it: ``"user"`` (the end user of an application, the
            default), ``"reviewer"`` (a person who reviews outputs) or
            ``"automatic"`` (a check run by a program or a model).
        items: The corrections, at least one for ``"correction"``, none for
            ``"rating"``.
        rating: ``"good"`` or ``"bad"``, only for ``"rating"``.
        comment: Free text, with either kind.
        external_ref: Opaque reference to the document of the consumer, for example
            ``{"system": "bedita", "object_id": "42", "revision": "3"}``.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    kind: Literal["correction", "rating"]
    source: Literal["user", "reviewer", "automatic"] = "user"
    items: list[Correction] = Field(default_factory=list, max_length=MAX_ITEMS)
    rating: Literal["good", "bad"] | None = None
    comment: str | None = None
    external_ref: dict[str, str] | None = None

    @model_validator(mode="after")
    def _matches_kind(self) -> Self:
        if self.kind == "correction" and (not self.items or self.rating is not None):
            raise ValueError("a correction has at least one item and no rating")
        if self.kind == "rating" and (self.rating is None or self.items):
            raise ValueError("a rating has a rating and no items")
        return self


class Feedback(FeedbackRequest):
    """Feedback as recorded with its run.

    Attributes:
        id: Identifier of the feedback.
        run_id: The run it is about.
        caller: Name of the caller that added it; ``None`` for trusted code.
        end_user: The end user the caller acted for, if any.
        created_at: When it was added.
    """

    id: str
    run_id: str
    caller: str | None
    end_user: str | None
    created_at: datetime
